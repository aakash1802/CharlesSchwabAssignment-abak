"""Developer agent — file changes only via Workspace (LLM or stub)."""

from __future__ import annotations

import json
import uuid
from dataclasses import dataclass, field

from agentic_engineer.agents.codegen_context import (
    CodegenContext,
    is_mock_without_queue,
)
from agentic_engineer.agents.diagnostics import record_developer_attempt
from agentic_engineer.agents.file_commit import commit_staged_files, validate_generated_files
from agentic_engineer.agents.prompt_loader import load_prompt
from agentic_engineer.config.settings import get_settings
from agentic_engineer.llm.base import LLMError, LLMProvider, LLMRequest, LLMResponse
from agentic_engineer.llm.failures import (
    ClassifiedLLMError,
    FailureCategory,
    format_classified_message,
)
from agentic_engineer.llm.structured_parse import parse_structured_model
from agentic_engineer.models.developer import (
    DeveloperFilesResponse,
    GeneratedFile,
    developer_files_json_schema,
)
from agentic_engineer.models.execution import DestructiveProposal
from agentic_engineer.models.task import Task
from agentic_engineer.workspace.workspace import Workspace

# Defaults (overridable via Settings when present).
_DEFAULT_MAX_FILES_PER_BATCH = 5
_DEFAULT_MAX_BATCHES = 4
_DEFAULT_STRUCTURED_ATTEMPTS = 2
_DEFAULT_DEV_MAX_TOKENS = 8192


@dataclass(frozen=True)
class DeveloperResult:
    written_paths: list[str]
    destructive: DestructiveProposal | None = None
    summary: str = ""
    implementation_decisions: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)


def _stub_write(workspace: Workspace, task: Task) -> DeveloperResult:
    rel = f"src/generated/{task.id}.py"
    body = (
        f'"""Generated by Developer agent for task {task.id}: {task.name}."""\n'
        f"TASK_ID = {task.id!r}\n"
        f"TASK_NAME = {task.name!r}\n"
        "\n"
        "def marker() -> str:\n"
        f"    return {task.id!r}\n"
    )
    workspace.write_text(rel, body)
    return DeveloperResult(written_paths=[rel], summary=f"Wrote {rel}")


class DeveloperAgent:
    def __init__(self, provider: LLMProvider) -> None:
        self._provider = provider
        self._system = load_prompt("developer_agent.txt")

    def apply_task(
        self,
        *,
        workspace: Workspace,
        task: Task,
        force_destructive: bool = False,
        context: CodegenContext | None = None,
    ) -> DeveloperResult:
        """Create/modify files for a developer task via Workspace only."""
        if force_destructive:
            proposal = DestructiveProposal(
                proposal_id=f"des_{uuid.uuid4().hex[:10]}",
                action="delete_tree",
                paths=["build/", "dist/"],
                reason=f"Task {task.id} requested removal of build artifacts",
                task_id=task.id,
            )
            return DeveloperResult(
                written_paths=[],
                destructive=proposal,
                summary="Destructive action proposed; awaiting approval",
            )

        if is_mock_without_queue(self._provider):
            return _stub_write(workspace, task)

        settings = get_settings()
        max_files = int(
            getattr(settings, "developer_max_files_per_batch", _DEFAULT_MAX_FILES_PER_BATCH)
        )
        max_batches = int(
            getattr(settings, "developer_max_batches", _DEFAULT_MAX_BATCHES)
        )
        structured_attempts = int(
            getattr(
                settings,
                "developer_structured_attempts",
                _DEFAULT_STRUCTURED_ATTEMPTS,
            )
        )
        max_tokens = max(
            int(getattr(settings, "llm_max_tokens", 4096) or 4096),
            _DEFAULT_DEV_MAX_TOKENS,
        )

        ctx = context or CodegenContext(task=task)
        pending: list[GeneratedFile] = []
        summaries: list[str] = []
        decisions: list[str] = []
        warnings: list[str] = []
        already: list[str] = []
        attempt = 0
        batch_size = max_files
        feedback: str | None = None

        try:
            for batch_index in range(max_batches):
                batch_ok = False
                last_error: ClassifiedLLMError | None = None
                for regen in range(structured_attempts):
                    attempt += 1
                    try:
                        response, parsed = self._generate_batch(
                            ctx=ctx,
                            task=task,
                            already=already,
                            batch_size=batch_size,
                            max_tokens=max_tokens,
                            feedback=feedback,
                        )
                        record_developer_attempt(
                            workspace,
                            task_id=task.id,
                            attempt=attempt,
                            provider=str(
                                (response.raw or {}).get("provider") or "unknown"
                            ),
                            model=response.model,
                            stop_reason=response.stop_reason,
                            token_usage=response.usage or {},
                            response_type=response.response_type,
                            parsing_outcome="ok",
                            validation_outcome="pending",
                            failure_category=None,
                            retry_decision="validate",
                            raw_response=response.text,
                            extra={"batch_index": batch_index, "regen": regen},
                        )
                        staged = validate_generated_files(
                            workspace, parsed.files, max_files=batch_size
                        )
                        # Stage into memory only; commit once after all batches.
                        for item in staged:
                            pending.append(
                                GeneratedFile(
                                    path=item.relative_path,
                                    content=item.content,
                                    action=item.action,  # type: ignore[arg-type]
                                )
                            )
                            already.append(item.relative_path)
                        if parsed.summary:
                            summaries.append(parsed.summary)
                        decisions.extend(parsed.implementation_decisions)
                        warnings.extend(parsed.warnings)
                        feedback = None
                        batch_ok = True
                        more = parsed.more_files_remaining
                        record_developer_attempt(
                            workspace,
                            task_id=task.id,
                            attempt=attempt,
                            provider=str(
                                (response.raw or {}).get("provider") or "unknown"
                            ),
                            model=response.model,
                            stop_reason=response.stop_reason,
                            token_usage=response.usage or {},
                            response_type=response.response_type,
                            parsing_outcome="ok",
                            validation_outcome="ok",
                            failure_category=None,
                            retry_decision="continue" if more else "commit",
                            extra={
                                "batch_index": batch_index,
                                "files": [s.relative_path for s in staged],
                            },
                        )
                        if not more:
                            written = self._commit_all(
                                workspace, pending, max_files=max_files * max_batches
                            )
                            return DeveloperResult(
                                written_paths=written,
                                summary="; ".join(summaries)
                                or f"Wrote {len(written)} file(s)",
                                implementation_decisions=decisions,
                                warnings=warnings,
                            )
                        break
                    except ClassifiedLLMError as exc:
                        last_error = self._prefer_error(last_error, exc)
                        feedback = str(exc)
                        record_developer_attempt(
                            workspace,
                            task_id=task.id,
                            attempt=attempt,
                            provider="unknown",
                            model="",
                            stop_reason=None,
                            token_usage={},
                            response_type="error",
                            parsing_outcome=(
                                "failed"
                                if exc.category
                                in {
                                    FailureCategory.INVALID_STRUCTURED_OUTPUT,
                                    FailureCategory.TRUNCATED_RESPONSE,
                                    FailureCategory.OUTPUT_TRUNCATED,
                                }
                                else "n/a"
                            ),
                            validation_outcome=(
                                "failed"
                                if exc.category
                                in {
                                    FailureCategory.SCHEMA_VALIDATION,
                                    FailureCategory.WORKSPACE_SAFETY,
                                    FailureCategory.WORKSPACE_VIOLATION,
                                    FailureCategory.INVALID_FILE_OPERATION,
                                    FailureCategory.PERMISSION_FAILURE,
                                }
                                else "n/a"
                            ),
                            failure_category=exc.category.value,
                            retry_decision=self._local_retry_decision(
                                exc, regen, structured_attempts
                            ),
                            raw_response=None,
                            extra={"batch_index": batch_index, "regen": regen},
                        )
                        if exc.category in {
                            FailureCategory.WORKSPACE_SAFETY,
                            FailureCategory.INVALID_FILE_OPERATION,
                        }:
                            raise last_error.with_prefix(
                                f"Developer agent failed for {task.id} ({task.name})"
                            ) from exc
                        if exc.category in {
                            FailureCategory.TRUNCATED_RESPONSE,
                            FailureCategory.OUTPUT_TRUNCATED,
                        }:
                            # Reduce scope instead of repeating the same oversized call.
                            batch_size = max(1, batch_size // 2)
                            max_tokens = min(max_tokens, max(2048, max_tokens))
                            continue
                        if regen + 1 >= structured_attempts:
                            break
                        continue
                    except LLMError as exc:
                        classified = ClassifiedLLMError(
                            str(exc),
                            category=FailureCategory.TRANSIENT_PROVIDER,
                        )
                        last_error = self._prefer_error(last_error, classified)
                        break

                if not batch_ok:
                    err = last_error or ClassifiedLLMError(
                        "Developer structured output failed",
                        category=FailureCategory.INVALID_STRUCTURED_OUTPUT,
                    )
                    raise err.with_prefix(
                        f"Developer agent failed for {task.id} ({task.name})"
                    )

            # Exhausted batches with more_files_remaining still true — commit what we have.
            if pending:
                written = self._commit_all(
                    workspace, pending, max_files=max_files * max_batches
                )
                warnings.append(
                    f"Reached max batches ({max_batches}); committed {len(written)} file(s)"
                )
                return DeveloperResult(
                    written_paths=written,
                    summary="; ".join(summaries) or f"Wrote {len(written)} file(s)",
                    implementation_decisions=decisions,
                    warnings=warnings,
                )
            raise ClassifiedLLMError(
                format_classified_message(
                    f"Developer agent failed for {task.id} ({task.name}): "
                    "no files generated",
                    FailureCategory.SCHEMA_VALIDATION,
                ),
                category=FailureCategory.SCHEMA_VALIDATION,
            )
        except ClassifiedLLMError:
            raise
        except LLMError as exc:
            raise ClassifiedLLMError(
                format_classified_message(
                    f"Developer agent failed for {task.id} ({task.name}): {exc}",
                    FailureCategory.IMPLEMENTATION,
                ),
                category=FailureCategory.IMPLEMENTATION,
            ) from exc

    def _generate_batch(
        self,
        *,
        ctx: CodegenContext,
        task: Task,
        already: list[str],
        batch_size: int,
        max_tokens: int,
        feedback: str | None,
    ) -> tuple[LLMResponse, DeveloperFilesResponse]:
        payload = ctx.to_prompt_payload()
        payload["generation"] = {
            "max_files_this_batch": batch_size,
            "already_written_paths": list(already),
            "batch_instruction": (
                f"Return at most {batch_size} related files for this task. "
                "Set more_files_remaining=true if additional files are still required."
            ),
        }
        if feedback:
            payload["prior_attempt_feedback"] = feedback

        request = LLMRequest(
            prompt=json.dumps(payload, indent=2) + "\n\nReturn structured JSON only.",
            system=self._system,
            response_schema_name="DeveloperFiles",
            response_json_schema=developer_files_json_schema(),
            max_tokens=max_tokens,
        )
        response = self._provider.complete(request)
        parsed = parse_structured_model(response, DeveloperFilesResponse)
        if not parsed.files and not parsed.more_files_remaining:
            raise ClassifiedLLMError(
                "Developer response contained no files",
                category=FailureCategory.SCHEMA_VALIDATION,
            )
        return response, parsed

    def _commit_all(
        self,
        workspace: Workspace,
        files: list[GeneratedFile],
        *,
        max_files: int,
    ) -> list[str]:
        # Last write wins when later batches revise an earlier path.
        deduped: dict[str, GeneratedFile] = {}
        for item in files:
            deduped[item.path.replace("\\", "/")] = item
        # Re-validate the full pending set before any filesystem write.
        staged = validate_generated_files(
            workspace, list(deduped.values()), max_files=max_files
        )
        return commit_staged_files(workspace, staged)

    @staticmethod
    def _prefer_error(
        previous: ClassifiedLLMError | None,
        current: ClassifiedLLMError,
    ) -> ClassifiedLLMError:
        """Keep the first high-signal failure when a later regen is low-signal."""
        if previous is None:
            return current
        high_signal = {
            FailureCategory.INVALID_STRUCTURED_OUTPUT,
            FailureCategory.TRUNCATED_RESPONSE,
            FailureCategory.OUTPUT_TRUNCATED,
            FailureCategory.TRANSIENT_PROVIDER,
            FailureCategory.RATE_LIMIT,
            FailureCategory.WORKSPACE_SAFETY,
            FailureCategory.WORKSPACE_VIOLATION,
            FailureCategory.INVALID_FILE_OPERATION,
            FailureCategory.PERMISSION_FAILURE,
        }
        if (
            previous.category in high_signal
            and current.category == FailureCategory.SCHEMA_VALIDATION
        ):
            return previous
        return current

    @staticmethod
    def _local_retry_decision(
        exc: ClassifiedLLMError, regen: int, structured_attempts: int
    ) -> str:
        if exc.category in {
            FailureCategory.WORKSPACE_SAFETY,
            FailureCategory.WORKSPACE_VIOLATION,
            FailureCategory.INVALID_FILE_OPERATION,
            FailureCategory.PERMISSION_FAILURE,
        }:
            return "stop"
        if regen + 1 >= structured_attempts:
            return "escalate"
        if exc.category in {
            FailureCategory.TRUNCATED_RESPONSE,
            FailureCategory.OUTPUT_TRUNCATED,
        }:
            return "reduce_scope_and_retry"
        return "regenerate"
